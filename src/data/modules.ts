function legacyEboardType(spec: ModuleSpec): string {
  const map: Partial<Record<ModuleSpec['category'], string>> = {
    mcb: 'mcb',
    rcd: 'rcd',
    rcbo: 'rcbo',
    afdd: 'afdd',
    spd: 'spd',
    contactor: 'contactor',
    relay: 'relay',
    meter: 'meter',
    switch: 'changeover',
    distribution: 'dist-block',
    terminal: 'terminal',
    busbar: 'dist-block',
    other: 'custom',
  }
  if (spec.id === 'switch-1-0-2') return 'changeover'
  if (spec.id === 'relay-timer') return 'relay-time'
  if (spec.id === 'relay-voltage-63') return 'relay-voltage'
  if (spec.id === 'relay-impulse') return 'relay-time'
  return map[spec.category] ?? 'custom'
}

